export function errorText(err: unknown): string {
  const code = (err as { code?: string } | null)?.code;
  return (code && (t.errors as Record<string, string>)[code]) || t.common.error;
}

export const timeAgo = (iso: string, now = new Date()) => shortAgo(iso, now, locale);

const TZ = 'Europe/Istanbul';
const fmt = (o: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(lang, { timeZone: TZ, ...o });
const dayFmt = fmt({ day: 'numeric', month: 'long', year: 'numeric' });
const longDayFmt = fmt({ weekday: 'long', day: 'numeric', month: 'long' });
const timeFmt = fmt({ hour: '2-digit', minute: '2-digit' });
const fullFmt = fmt({ hour: '2-digit', minute: '2-digit', day: 'numeric', month: 'long', year: 'numeric' });
const monthFmt = fmt({ month: 'long', year: 'numeric' });

export const formatDay = (iso: string) => dayFmt.format(new Date(iso));
export const formatLongDay = (iso: string) => longDayFmt.format(new Date(iso));
export const formatTime = (iso: string) => timeFmt.format(new Date(iso));
export const formatFull = (iso: string) => fullFmt.format(new Date(iso));
export const formatMonth = (iso: string) => monthFmt.format(new Date(iso));
export const formatNumber = (n: number) => n.toLocaleString(lang);
