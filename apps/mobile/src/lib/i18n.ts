export function errorText(err: unknown): string {
  const code = (err as { code?: string } | null)?.code;
  return (code && (t.errors as Record<string, string>)[code]) || t.errors.default;
}

const dateFmt = new Intl.DateTimeFormat(locale === 'tr' ? 'tr-TR' : 'en-US', {
  weekday: 'long',
  day: 'numeric',
  month: 'long',
  hour: '2-digit',
  minute: '2-digit',
  timeZone: 'Europe/Istanbul',
});
export const formatEventDate = (iso: string) => dateFmt.format(new Date(iso));

const dayFmt = new Intl.DateTimeFormat(locale === 'tr' ? 'tr-TR' : 'en-US', { day: 'numeric', month: 'long', year: 'numeric' });
export const formatDay = (iso: string) => dayFmt.format(new Date(iso));

// Hermes `Intl.RelativeTimeFormat` taşımıyor; akıştaki "3 saat önce" metni elle kuruluyor.
const units = {
  tr: { now: 'az önce', m: 'dk', h: 'sa', d: 'g', ago: 'önce' },
  en: { now: 'just now', m: 'm', h: 'h', d: 'd', ago: 'ago' },
}[locale];
export function timeAgo(iso: string): string {
  const minutes = Math.floor((Date.now() - new Date(iso).getTime()) / 60_000);
  if (minutes < 1) return units.now;
  if (minutes < 60) return `${minutes} ${units.m} ${units.ago}`;
  if (minutes < 1440) return `${Math.floor(minutes / 60)} ${units.h} ${units.ago}`;
  if (minutes < 10_080) return `${Math.floor(minutes / 1440)} ${units.d} ${units.ago}`;
  return formatDay(iso);
}
